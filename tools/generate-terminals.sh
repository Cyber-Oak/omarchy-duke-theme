#!/bin/bash
# Render the four terminal configs from colors.toml through Omarchy's own
# templates, then add the glass: alpha on the cell background only (text stays
# opaque) and a request for compositor blur. Re-run after editing colors.toml.
#
#   tools/generate-terminals.sh

set -euo pipefail

THEME_DIR=$(cd "$(dirname "$0")/.." && pwd)
TEMPLATES="${OMARCHY_PATH:-/usr/share/omarchy}/default/themed"
ALPHA=0.72

sed_script=$(mktemp)
trap 'rm -f "$sed_script"' EXIT

# omarchy-theme-color resolves aliases (purple, colorN, ...) the same way
# omarchy-theme-set-templates does.
while IFS=$'\t' read -r key value; do
  printf 's|{{ %s }}|%s|g\n' "$key" "$value" >>"$sed_script"
  printf 's|{{ %s_strip }}|%s|g\n' "$key" "${value#\#}" >>"$sed_script"
done < <(omarchy-theme-color --file "$THEME_DIR/colors.toml" --all)

render() {
  local name="$1" header="$2"
  {
    printf '%s\n' "$header"
    sed -f "$sed_script" "$TEMPLATES/$name.tpl"
  } >"$THEME_DIR/$name"
  if grep -q '{{' "$THEME_DIR/$name"; then
    echo "Unresolved template keys in $name" >&2
    exit 1
  fi
}

note="# Duke — generated by tools/generate-terminals.sh from colors.toml. Do not edit."

render ghostty.conf "$note
background-opacity = $ALPHA
# Ask Hyprland for blur explicitly.
background-blur = true"

render kitty.conf "$note
background_opacity $ALPHA
background_blur 1"

# foot: the alpha/blur keys belong in [colors-dark], so insert after the header.
render foot.ini "$note
# blur=yes is required: a foot built with blur support otherwise tells the
# compositor not to blur behind it."
sed -i "s/^\[colors-dark\]$/[colors-dark]\nalpha=$ALPHA\nblur=yes/" "$THEME_DIR/foot.ini"

render alacritty.toml "$note
[window]
opacity = $ALPHA
blur = true
"

echo "Wrote ghostty.conf kitty.conf foot.ini alacritty.toml"
